    public static object is_in_sight(atom first_atom = null, atom second_atom = null)
    {
        turf first_turf = get_turf(first_atom);
        turf second_turf = get_turf(second_atom);

        if (first_turf == null || second_turf == null)
            return FALSE;

        return inLineOfSight(first_turf.x, first_turf.y, second_turf.x, second_turf.y, first_turf.z);
    }
