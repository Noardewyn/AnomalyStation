using System.Reflection;
using System.Text;

namespace Anomaly.Tools.Types;

/// <summary>
/// Builds every output of the tool from the model (types-converter.md): the generated classes, the type order, the
/// type/proc index and the conformance data. Deterministic: the same model, sources and Tg assembly give the same bytes.
/// </summary>
internal sealed partial class Generator
{
    private readonly TgModel _model;
    private readonly string _repo;
    private readonly TextWriter _log;
    private readonly Dictionary<string, Node> _nodes = new(StringComparer.Ordinal);
    private readonly List<Node> _preorder = new();
    private Node _datum;
    private HandWritten _hand;
    private Translation _translation;
    private CSharpValues _values;
    private readonly HashSet<string> _nullUsed;
    private readonly HashSet<string> _typepathAssigned;

    /// <summary>One line per decision the lead reviews (types-converter.md 3.4): gaps, clashes, skipped types.</summary>
    public readonly List<string> Report = new();

    public readonly SortedDictionary<string, int> GapCounts = new(StringComparer.Ordinal);

    public Generator(TgModel model, string repo, TextWriter log)
    {
        _model = model;
        _repo = repo;
        _log = log;
        _nullUsed = new HashSet<string>(model.NullUsed ?? new(), StringComparer.Ordinal);
        _typepathAssigned = new HashSet<string>(model.TypepathAssigned ?? new(), StringComparer.Ordinal);
    }

    public string Header(string what) =>
        "// <auto-generated>\n"
        + $"// Generated by tools/Anomaly.Tools.Types (docs/ai/specs/types-converter.md): {what}.\n"
        + $"// From tgstation {_model.TgCommit} (snapshot {Clones.TgPin}), compiled by OpenDream {_model.OpenDreamCommit}\n"
        + $"// (RobustToolbox {_model.RobustToolboxCommit}) with {_model.Defines}. Do not edit; rerun the tool.\n"
        + "// </auto-generated>\n"
        + "// Derived from tgstation code. Original copyright and license: tgstation, AGPL-3.0 (code). See ../tgstation/LICENSE.\n";

    public string HashHeader(string what) => string.Join("\n", Header(what).TrimEnd('\n').Split('\n')
        .Where(l => !l.Contains("auto-generated", StringComparison.Ordinal))
        .Select(l => "#" + l.Substring(2))) + "\n";

    public Outputs Run()
    {
        _hand = HandWritten.Scan(Path.Combine(_repo, "src", "Core", "Tg"));
        _translation = new Translation();
        BuildTree();
        AssignModes();
        AssignNames();
        _values = new CSharpValues(p => _nodes.GetValueOrDefault(p));
        DecideMembers();
        var outputs = new Outputs();
        ReadLivePartial();
        ReadOrFreezeLiveBase(outputs);
        DecideInert();

        EmitClasses(outputs);
        EmitLivePartial(outputs);
        EmitUndeclaredOverrides(outputs);
        EmitTypeOrder(outputs);
        EmitIndex(outputs);
        EmitConformance(outputs);
        EmitIconSizes(outputs);
        foreach (var (k, v) in GapCounts) Report.Add($"gap count: {k}: {v}");
        outputs.Report = Report;
        _log.WriteLine($"types: {_preorder.Count}, generated {_preorder.Count(n => n.Mode == Mode.Generated)}, hand {_preorder.Count(n => n.Mode == Mode.Hand)}, hand-procs {_preorder.Count(n => n.Mode == Mode.HandProcs)}, skipped {_preorder.Count(n => n.Mode == Mode.Skip)}, inert {_preorder.Count(n => n.Inert)}");
        return outputs;
    }

    private void Gap(string kind, string line)
    {
        GapCounts[kind] = GapCounts.GetValueOrDefault(kind) + 1;
        Report.Add(kind + ": " + line);
    }

    // ---- the tree ------------------------------------------------------------------------------------------------

    /// <summary>OpenDream's artefact types (a VAR_PRIVATE block parsed as a type, types-converter.md 2.1).</summary>
    public static bool IsArtefact(string path) => path.Split('/').Skip(1).Any(s => s is "var" or "proc" or "verb");

    private void BuildTree()
    {
        foreach (TypeInfo t in _model.Types.OrderBy(t => t.Id))
        {
            if (t.Path == "/" || IsArtefact(t.Path))
            {
                if (t.Path != "/") Report.Add($"skipped OpenDream artefact type {t.Path} (no vars, no procs)");
                continue;
            }
            _nodes[t.Path] = new Node { Info = t };
        }
        foreach (Node n in _nodes.Values.OrderBy(n => n.Info.Id))
        {
            if (n.Info.Parent != null && n.Info.Parent != "/" && _nodes.TryGetValue(n.Info.Parent, out Node p))
            {
                n.Parent = p;
                p.Children.Add(n);
            }
        }
        foreach (Node root in _nodes.Values.Where(n => n.Parent == null).OrderBy(n => n.Info.Id))
            Preorder(root, 0);
        _datum = _nodes["/datum"];
        foreach (string m in _model.MetaTypes ?? new())
            for (Node n = _nodes.GetValueOrDefault(m); n != null; n = n.Parent) n.InMeta = true;
    }

    private void Preorder(Node n, int depth)
    {
        n.Depth = depth;
        _preorder.Add(n);
        foreach (Node c in n.Children) Preorder(c, depth + 1);
    }

    private void AssignModes()
    {
        var shim = new Dictionary<string, Type>(StringComparer.Ordinal);
        foreach (Type t in typeof(Anomaly.Core.DmShim.Dm).Assembly.GetTypes())
        {
            var p = t.GetCustomAttribute<Anomaly.Core.DmShim.DmPathAttribute>(false);
            if (p != null) shim[p.Path] = t;
        }
        foreach (Node n in _preorder)
        {
            if (shim.TryGetValue(n.Path, out Type st))
            {
                n.Mode = Mode.Skip;
                n.Existing = st;
                n.ClassName = st.Name;
                n.SkipReason = "the shim implements it (" + st.Name + ")";
                continue;
            }
            HandWritten.ClassParts hand = _hand.ByPath(n.Path) ?? _hand.Classes.GetValueOrDefault(RuleName(n.Path));
            if (hand != null && (hand.DmPath == null || hand.DmPath == n.Path))
            {
                n.Hand = hand;
                n.ClassName = hand.Name;
                n.Existing = _translation.ClassByPath.GetValueOrDefault(n.Path);
                bool varBlock = hand.HasConstructor || hand.HasInitVars || hand.HasTgVars
                    || n.Info.Vars.Any(v => hand.Fields.Contains(v.Name) || hand.Properties.Contains(v.Name));
                n.Mode = varBlock ? Mode.Hand : Mode.HandProcs;
                continue;
            }
            if (n.Parent != null && n.Parent.Mode == Mode.Skip && n.Parent.Existing == null)
            {
                n.Mode = Mode.Skip;
                n.SkipReason = "a subtype of " + n.Parent.Path + ", which has no class";
                continue;
            }
            if (n.Info.Builtin)
            {
                n.Mode = Mode.Skip;
                n.SkipReason = "a BYOND builtin type without an engine part";
                continue;
            }
            n.Mode = Mode.Generated;
        }
        foreach (Node n in _preorder.Where(n => n.Mode == Mode.Skip && n.Existing == null))
            Report.Add($"no class: {n.Path}: {n.SkipReason}");
    }

    public static string RuleName(string path) => path.TrimStart('/').Replace('/', '_');

    private void AssignNames()
    {
        // Rules 2.3: the path without the leading '/', '/' -> '_'; of two paths with one name, the one with fewer
        // segments gets __2. Hand-written and shim classes keep their names.
        var taken = new Dictionary<string, Node>(StringComparer.Ordinal);
        foreach (Node n in _preorder.Where(n => n.ClassName != null)) taken[n.ClassName] = n;
        var groups = _preorder.Where(n => n.ClassName == null && n.Mode == Mode.Generated)
            .GroupBy(n => RuleName(n.Path), StringComparer.Ordinal);
        foreach (var g in groups)
        {
            var members = g.ToList();
            if (taken.TryGetValue(g.Key, out Node owner)) members.Add(owner);
            if (members.Count == 1) { members[0].ClassName = g.Key; continue; }
            // Most segments keep the plain name; the others get __2, __3, ... by fewer segments, then path order.
            var ordered = members.OrderByDescending(m => m.Path.Count(c => c == '/')).ThenBy(m => m.Path, StringComparer.Ordinal).ToList();
            for (int i = 0; i < ordered.Count; i++)
            {
                Node m = ordered[i];
                string name = i == 0 ? g.Key : g.Key + "__" + (i + 1);
                if (m.ClassName != null && m.ClassName != name)
                    Report.Add($"name collision: {m.Path} keeps its hand-written name {m.ClassName} (rules 2.3 would give {name})");
                m.ClassName ??= name;
            }
            Report.Add("name collision (rules 2.3): " + string.Join(", ", ordered.Select(m => m.Path + " -> " + m.ClassName)));
        }
        // Classes of the Tg assembly that are not DM types must not be hidden by a generated name.
        var other = new HashSet<string>(_translation.TgAssembly.GetTypes().Where(t => t.Namespace == "Anomaly.Core.Tg" && !t.IsNested)
            .Where(t => t.GetCustomAttribute<Anomaly.Core.DmShim.DmPathAttribute>(false) == null).Select(t => t.Name), StringComparer.Ordinal);
        foreach (Node n in _preorder.Where(n => n.Mode == Mode.Generated && other.Contains(n.ClassName) && !_hand.Classes.ContainsKey(n.ClassName)))
            Report.Add($"name clash: generated class {n.ClassName} ({n.Path}) has the name of a non-DM class of the Tg assembly");
    }
}
