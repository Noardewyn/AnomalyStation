    /**
     * When passed a "character", returns the name of the character formatted for stories
     *
     * If character is a string, it will just return it back.
     *
     * Otherwise, it will try to generate a title based on the mob's assigned role.
     *
     * If the character has no mind or no assigned role, it'll just return their name.
     */
    // tg: code/datums/memory/_memory.dm:378
    public virtual object build_story_character(object character = null)
    {
        if (character == null)
            return null;
        if (istext(character))
            return character;

        if (isliving(character))
        {
            mob_living living_character = character as mob_living;
            if (living_character.mind != null && !is_unassigned_job(living_character.mind.assigned_role))
                character = living_character.mind;

            else if (ishuman(character))
                // This can slip into memories involving monkey humans.
                return I18n.T("the unfamiliar person");
        }

        if (character is datum_mind character_mind)
            return I18n.T("\\the []", LOWER_TEXT(Dm.initial(character_mind.assigned_role, (datum_job job) => job.title)));

        // Generic result - mobs get "the guy", objs / turfs get "a thing"
        return ismob(character) ? I18n.T("\\the []", character) : I18n.T("\\a []", character);
    }

