///Fish movements are simple datums, generated by the fishing minigame, that represent how the fish moves suring the minigame.
// tg: code/modules/fishing/fish_movement.dm:11
public partial class datum_fish_movement : datum
{
    /// Any lower than this, and the target position of the fish is considered null
    // tg: code/modules/fishing/fish_movement.dm:2  #define FISH_TARGET_MIN_DISTANCE 6
    protected const float FISH_TARGET_MIN_DISTANCE = 6;
    /// The friction applied to fish jumps, so that it decelerates over time
    // tg: code/modules/fishing/fish_movement.dm:4  #define FISH_FRICTION_MULT 0.9
    protected const float FISH_FRICTION_MULT = 0.9f;
    /// Used to decide whether the fish can jump in a certain direction
    // tg: code/modules/fishing/fish_movement.dm:6  #define FISH_SHORT_JUMP_MIN_DISTANCE 100
    protected const float FISH_SHORT_JUMP_MIN_DISTANCE = 100;
    /// The maximum distance for a short jump
    // tg: code/modules/fishing/fish_movement.dm:8  #define FISH_SHORT_JUMP_MAX_DISTANCE 200
    protected const float FISH_SHORT_JUMP_MAX_DISTANCE = 200;

    // tg: code/modules/fishing/fish_movement.dm:35
    [DmParams("master")]
    public override async DmTask New(params object[] __extra)
    {
        this.master = Dm.arg<datum_fishing_challenge>(__extra, 0);
        await DmTask.CompletedTask;
    }

    /**
     * Proc that adjusts movement values to the difficulty of the minigame.
     * The operations can be a tad complex, but basically it ensures that jump
     * chances with a probability higher than 1% increase in a smooth curve so that
     * they still reach 100% prob when the difficulty peakes.
     */
    // tg: code/modules/fishing/fish_movement.dm:44
    public virtual void adjust_to_difficulty()
    {
        float square_angle_rad = TORADIANS(90);
        float zero_one_difficulty = master.difficulty / 100;
        if (short_jump_chance > 1)
            short_jump_chance = (float)Math.Pow(zero_one_difficulty, square_angle_rad - TORADIANS(arctan(short_jump_chance * 1 / square_angle_rad))) * 100;
        else
            short_jump_chance *= master.difficulty;
        if (long_jump_chance > 1)
            long_jump_chance = (float)Math.Pow(zero_one_difficulty, square_angle_rad - TORADIANS(arctan(long_jump_chance * 1 / square_angle_rad))) * 100;
        else
            long_jump_chance *= master.difficulty;
    }

    // tg: code/modules/fishing/fish_movement.dm:56
    public virtual void reset_difficulty_values()
    {
        short_jump_chance = Dm.num(Dm.initial(this, (datum_fish_movement p) => p.short_jump_chance));
        long_jump_chance = Dm.num(Dm.initial(this, (datum_fish_movement p) => p.long_jump_chance));
    }

    ///The main proc, called by minigame every SSfishing tick while it's in the 'active' phase.
    // tg: code/modules/fishing/fish_movement.dm:61
    public virtual void move_fish(object seconds_per_tick = null)
    {
        float spt = Dm.num(seconds_per_tick);
        times_fired++;
        /**
         * The jump chances are meant to run every odd tick (each every decisecond)
         * We cannot do it every tick because the fish would be jumpier than intended
         * and we cannot cut the chances in half to fit on each tick, because the maximum probability
         *  would go from 100% to 75%.
         */
        bool can_roll = Dm.mod(times_fired, 2) != 0;

        float long_chance = long_jump_chance * spt * (1 / spt);
        float short_chance = short_jump_chance * spt * (1 / spt);

        // If we have the target but we're close enough, mark as target reached
        if (abs(Dm.num(target_position) - master.fish_position) < FISH_TARGET_MIN_DISTANCE)
            target_position = null;

        // Switching to new long jump target can interrupt any other
        if (can_roll && (Dm.truthy(can_interrupt_move) || target_position == null) && prob(long_chance))
        {
            /**
             * Move at least 0.75 to full of the availible bar in given direction,
             * and more likely to move in the direction where there's more space
             */
            float distance_from_top = FISHING_MINIGAME_AREA - master.fish_position - master.fish_height;
            float distance_from_bottom = master.fish_position;
            float top_chance;
            if (distance_from_top < FISH_SHORT_JUMP_MIN_DISTANCE)
                top_chance = 0;
            else
                top_chance = (distance_from_top / max(distance_from_bottom, 1)) * 100;
            float new_target = master.fish_position;
            if (prob(top_chance))
                new_target += distance_from_top * rand(75, 100) / 100;
            else
                new_target -= distance_from_bottom * rand(75, 100) / 100;
            target_position = round(new_target);
            current_velocity_limit = long_jump_velocity_limit;
        }

        // Move towards target
        if (target_position != null)
        {
            float distance = Dm.num(target_position) - master.fish_position;
            // about 5 at diff 15 , 10 at diff 30, 30 at diff 100
            float acceleration_mult = Dm.num(get_acceleration(seconds_per_tick));
            float target_acceleration = distance * acceleration_mult * spt;

            if (fish_idle_velocity != 0)
            {
                float idle_velocity = fish_idle_velocity;
                float abs_idle_vel = abs(idle_velocity);
                //Make sure idle velocity doesn't manage to halt fish to a grind and getting them unable to move.
                //First, check if the directions of the two forces are oppositve
                if ((idle_velocity / abs_idle_vel) != (target_acceleration / abs(target_acceleration)))
                {
                    //Then, calculate the ratio between absolute idle velocity and halved acceleration multiplier.
                    float halved_ratio = (acceleration_mult * 0.5f) / abs_idle_vel;
                    /**
                     * If the idle velocity is more than half the acceleration,
                     * proceed to use powers, for diminishing loss of acceleration per additional unit of idle velocity.
                     * This way you never reach 0 acceleration while allowing more extreme values to keep lowering it.
                     */
                    if (halved_ratio < 1)
                    {
                        float power = min(halved_ratio + 0.5f, 1);
                        // tg writes `halved_ratio^power` (:117): `^` is DM's bitwise xor of the two numbers, kept as tg has it.
                        target_acceleration *= 1 - Dm.num(Dm.bitxor(halved_ratio, power));
                    }
                    /**
                     * Otherwise we add the idle velocity (which we know is of opposite sign and
                     * has an absolute value between 0.ε and 0.5) to the target velocity
                     */
                    else
                        target_acceleration += idle_velocity;
                }
            }

            fish_velocity = fish_velocity * FISH_FRICTION_MULT + target_acceleration;
        }
        else if (can_roll && prob(short_chance))
        {
            float distance_from_top = FISHING_MINIGAME_AREA - master.fish_position - master.fish_height;
            float distance_from_bottom = master.fish_position;
            float jump_length = 0;
            if (distance_from_top >= FISH_SHORT_JUMP_MIN_DISTANCE)
                jump_length = rand(FISH_SHORT_JUMP_MIN_DISTANCE, FISH_SHORT_JUMP_MAX_DISTANCE);
            if (distance_from_bottom >= FISH_SHORT_JUMP_MIN_DISTANCE && (jump_length == 0 || prob(50)))
                jump_length = -rand(FISH_SHORT_JUMP_MIN_DISTANCE, FISH_SHORT_JUMP_MAX_DISTANCE);
            target_position = clamp(master.fish_position + jump_length, 0, FISHING_MINIGAME_AREA - master.fish_height);
            current_velocity_limit = short_jump_velocity_limit;
        }

        fish_velocity = clamp(fish_velocity, -Dm.num(current_velocity_limit), Dm.num(current_velocity_limit));
        set_fish_position(seconds_per_tick);
    }

    ///Proc that returns the acceleration of the fish during the minigame.
    // tg: code/modules/fishing/fish_movement.dm:149
    public virtual object get_acceleration(object seconds_per_tick = null)
    {
        return 0.3f * master.difficulty + 0.5f;
    }

    ///Called at the end of move_fish(), for updating the position of the fish in the fishing minigame.
    // tg: code/modules/fishing/fish_movement.dm:153
    public virtual void set_fish_position(object seconds_per_tick = null)
    {
        master.fish_position = clamp(master.fish_position + fish_velocity * Dm.num(seconds_per_tick), 0, FISHING_MINIGAME_AREA - master.fish_height);
    }
}

///fish movement datum that progressively gets faster until acceleration and velocity are double the starting ones.
// tg: code/modules/fishing/fish_movement.dm:166
public partial class datum_fish_movement_accelerando : datum_fish_movement
{
    // tg: code/modules/fishing/fish_movement.dm:173
    public override void move_fish(object seconds_per_tick = null)
    {
        float spt = Dm.num(seconds_per_tick);
        float seconds_elapsed = times_fired * spt;
        if (seconds_elapsed >= accel_time_cap)
        {
            base.move_fish(seconds_per_tick);
            return;
        }
        if (times_fired == 0) //First tick, cache the initial jump velocities
        {
            short_jump_vel_add = short_jump_velocity_limit / accel_time_cap;
            long_jump_vel_add = long_jump_velocity_limit / accel_time_cap;
            base.move_fish(seconds_per_tick);
            return;
        }

        if (Dm.truthy(current_velocity_limit))
        {
            float vel_add = Dm.num(current_velocity_limit) == short_jump_velocity_limit ? Dm.num(short_jump_vel_add) : Dm.num(long_jump_vel_add);
            current_velocity_limit = Dm.num(current_velocity_limit) + round(vel_add * spt, 0.01f);
        }

        short_jump_velocity_limit += round(Dm.num(short_jump_vel_add) * spt, 0.01f);
        long_jump_velocity_limit += round(Dm.num(long_jump_vel_add) * spt, 0.01f);
        base.move_fish(seconds_per_tick);
    }

    // tg: code/modules/fishing/fish_movement.dm:190
    public override object get_acceleration(object seconds_per_tick = null)
    {
        float acceleration = Dm.num(base.get_acceleration(seconds_per_tick));
        return acceleration + min(acceleration, acceleration * times_fired * Dm.num(seconds_per_tick) / accel_time_cap);
    }

    // tg: code/modules/fishing/fish_movement.dm:194
    public override void set_fish_position(object seconds_per_tick = null)
    {
        fish_velocity = round(fish_velocity);
        base.set_fish_position(seconds_per_tick);
    }
}

///Fish movement datum that updates the fish position twice per second.
// tg: code/modules/fishing/fish_movement.dm:199
public partial class datum_fish_movement_choppy : datum_fish_movement
{
    // tg: code/modules/fishing/fish_movement.dm:203
    public override void set_fish_position(object seconds_per_tick = null)
    {
        faux_position = clamp(faux_position + fish_velocity * Dm.num(seconds_per_tick), 0, FISHING_MINIGAME_AREA - master.fish_height);
        if (!Dm.truthy(Dm.mod(times_fired * SSfishing.wait, 0.5f * SECONDS)))
            master.fish_position = faux_position;
    }
}

///Fish movement datum that weakly pushes the fish up and then down with greater force once it reaches the top of the minigame.
// tg: code/modules/fishing/fish_movement.dm:209
public partial class datum_fish_movement_plunger : datum_fish_movement
{
    // tg: code/modules/fishing/fish_movement.dm:215
    public override void adjust_to_difficulty()
    {
        base.adjust_to_difficulty();
        //Adjust the fleeing velocity, up to five times the initial value.
        plunging_speed += round(plunging_speed * master.difficulty * 0.03f);
        fish_idle_velocity += plunging_speed; //so it can be safely subtracted if the fish starts at the bottom.
    }

    // tg: code/modules/fishing/fish_movement.dm:221
    public override void reset_difficulty_values()
    {
        base.reset_difficulty_values();
        if (Dm.truthy(is_plunging))
            fish_idle_velocity -= plunging_speed;
        plunging_speed = Dm.num(Dm.initial(this, (datum_fish_movement_plunger p) => p.plunging_speed));
    }

    // tg: code/modules/fishing/fish_movement.dm:227
    public override void move_fish(object seconds_per_tick = null)
    {
        float fish_area = FISHING_MINIGAME_AREA - master.fish_height;
        if (Dm.truthy(is_plunging))
        {
            if (Dm.num(target_position) > master.fish_position) //nothing should stop us from plunging.
                target_position = null;
            float dist_bot_percent = master.fish_position / fish_area;
            if (dist_bot_percent <= 0.04f)
            {
                fish_idle_velocity -= plunging_speed;
                is_plunging = FALSE;
            }
        }
        else
        {
            float dist_top_percent = (fish_area - master.fish_position) / fish_area;
            if (dist_top_percent <= 0.04f)
            {
                fish_idle_velocity += plunging_speed;
                is_plunging = TRUE;
            }
        }

        base.move_fish(seconds_per_tick);
    }
}
