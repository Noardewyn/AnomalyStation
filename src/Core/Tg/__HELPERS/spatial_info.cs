    ///Calculate if two atoms are in sight, returns TRUE or FALSE
    // tg: code/__HELPERS/spatial_info.dm:253
    public static object inLineOfSight(float X1, float Y1, float X2, float Y2, float Z = 1, float PX1 = 16.5f, float PY1 = 16.5f, float PX2 = 16.5f, float PY2 = 16.5f)
    {
        turf current_turf;
        if (X1 == X2)
        {
            if (Y1 == Y2)
                return TRUE; //Light cannot be blocked on same tile
            else
            {
                float sign__1 = sign(Y2 - Y1);
                Y1 += sign__1;
                while (Y1 != Y2)
                {
                    current_turf = locate(X1, Y1, Z) as turf;
                    if (current_turf?.directional_opacity == ALL_CARDINALS) // IS_OPAQUE_TURF
                        return FALSE;
                    Y1 += sign__1;
                }
            }
        }
        else
        {
            //This looks scary but we're just calculating a linear function (y = mx + b)

            //m = y/x
            float m = (ICON_SIZE_Y * (Y2 - Y1) + (PY2 - PY1)) / (ICON_SIZE_X * (X2 - X1) + (PX2 - PX1)); //In pixels

            //b = y - mx
            float b = (Y1 + PY1 / ICON_SIZE_Y - OFFSET_Y) - m * (X1 + PX1 / ICON_SIZE_X - OFFSET_X); //In tiles

            float signX = sign(X2 - X1);
            float signY = sign(Y2 - Y1);
            if (X1 < X2)
                b += m;
            while (X1 != X2 || Y1 != Y2)
            {
                if (round(m * X1 + b - Y1) != 0) // Basically, if y >= mx+b
                    Y1 += signY; //Line exits tile vertically
                else
                    X1 += signX; //Line exits tile horizontally
                current_turf = locate(X1, Y1, Z) as turf;
                if (current_turf?.directional_opacity == ALL_CARDINALS) // IS_OPAQUE_TURF
                    return FALSE;
            }
        }
        return TRUE;
    }

