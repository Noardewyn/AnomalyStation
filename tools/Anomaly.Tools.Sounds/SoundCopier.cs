using System.Linq;
using System.IO;
using System.Text;
using System.Text.Json;
using Anomaly.Core.Tg;

namespace Anomaly.Tools.Sounds;

/// <summary>One line of <c>sound/index.json</c>.</summary>
public sealed class SoundIndexEntry
{
    /// <summary>The tg path, the key the server sends: <c>sound/machines/airlock/airlock.ogg</c>.</summary>
    public string Path { get; set; }

    /// <summary>The length in deciseconds (a fraction, as rust-g's sound_len reports it).</summary>
    public double Ds { get; set; }

    /// <summary>The sample rate in Hz.</summary>
    public int Rate { get; set; }

    /// <summary>The channel count (1: positional sounds are mono).</summary>
    public int Channels { get; set; }

    /// <summary>The licence label.</summary>
    public string Licence { get; set; }

    /// <summary>True when the licence forbids commercial use.</summary>
    public bool Nc { get; set; }

    /// <summary>True when the attribution names the sound but states no licence we recognise.</summary>
    public bool Unknown { get; set; }

    /// <summary>The attribution file that names the sound (relative to the clone's sound/), null for the default licence.</summary>
    public string Attribution { get; set; }

    /// <summary>"ogg", "mp3", or "wav" for a RIFF/WAVE file that tg names .ogg (Godot's Ogg loader cannot play it).</summary>
    public string Format { get; set; }

    /// <summary>The size of the file in bytes.</summary>
    public long Bytes { get; set; }

    /// <summary>Where the file was copied: "sound", "sound-nc", or null (absent: a non-commercial file under <c>--skip-nc</c>, or a file with no licence, D344).</summary>
    public string Where { get; set; }

    /// <summary>The copy's path relative to the output folder (null when absent): <c>sound/machines/airlock/airlock.ogg</c> or <c>sound-nc/...</c>.</summary>
    public string File { get; set; }
}

/// <summary>
/// The copy (M4b, the audio plan section 4.3): every <c>sound/**/*.ogg</c> of the tgstation clone is copied unchanged to
/// <c>&lt;out&gt;/sound/&lt;path below sound/&gt;</c> (the tg path <c>sound/x.ogg</c> is the key; the folder mirrors tg's), and
/// <c>&lt;out&gt;/sound/index.json</c> lists each with length, sample rate, channels and licence. Files under a non-commercial licence
/// go to <c>&lt;out&gt;/sound-nc/</c> beside a NOTICE (<c>--skip-nc</c> leaves them out and marks them absent). A file whose size and
/// modification time already match is not rewritten. tg's one .mp3 is copied as it is (the index says <c>mp3</c>); the .mid and
/// .mod files of tg's sound/ tree are skipped and counted. D344: <see cref="SoundLicences"/> corrects the licence of the files
/// whose source names one tg's text leaves out, and the files with no licence at all are indexed but never copied.
/// </summary>
public static class SoundCopier
{
    /// <summary>The first words of the SOURCE.txt paragraph (tools/Anomaly.Tools.Icons keeps a paragraph that starts with them when it rewrites the file).</summary>
    public const string SourceMarker = "Sounds: generated by tools/Anomaly.Tools.Sounds";

    private static readonly JsonSerializerOptions JsonOptions = new() { PropertyNamingPolicy = JsonNamingPolicy.CamelCase };

    /// <summary>Copies the sounds and writes the index; returns the exit code (0: done, 1: some file failed, 2: the input is no tgstation clone).</summary>
    public static int Run(SoundToolOptions options, TextWriter output, TextWriter errors)
    {
        string soundRoot = Path.Combine(options.TgRoot, "sound");
        if (!Directory.Exists(soundRoot))
        {
            errors.WriteLine($"Anomaly.Tools.Sounds: {soundRoot} does not exist (--tg must be a tgstation clone)");
            return 2;
        }

        var otherExtensions = new SortedDictionary<string, int>(StringComparer.Ordinal);
        var oggs = new List<string>();
        foreach (string file in Directory.EnumerateFiles(soundRoot, "*", SearchOption.AllDirectories))
        {
            string rel = Path.GetRelativePath(soundRoot, file).Replace('\\', '/');
            string ext = Path.GetExtension(rel).ToLowerInvariant();
            if (ext == ".ogg" || ext == ".mp3")
            {
                oggs.Add(rel);
                continue;
            }
            string key = ext.Length == 0 ? "(none)" : ext;
            otherExtensions[key] = otherExtensions.GetValueOrDefault(key) + 1;
        }
        oggs.Sort(StringComparer.Ordinal);

        Attributions attributions = Attributions.Load(soundRoot, oggs);

        string soundOut = Path.Combine(options.OutputDirectory, "sound");
        string ncOut = Path.Combine(options.OutputDirectory, "sound-nc");
        Directory.CreateDirectory(soundOut);
        // Godot must not import thousands of sounds: the client loads these files itself (the same .gdignore the icons use).
        string gdignore = Path.Combine(options.OutputDirectory, ".gdignore");
        if (!File.Exists(gdignore))
            File.WriteAllBytes(gdignore, Array.Empty<byte>());
        WriteSourceNote(Path.Combine(options.OutputDirectory, "SOURCE.txt"));

        var entries = new List<SoundIndexEntry>(oggs.Count);
        int copied = 0, upToDate = 0, failed = 0, absent = 0, unlicensed = 0;
        long totalBytes = 0, ncBytes = 0;
        foreach (string rel in oggs)
        {
            string source = Path.Combine(soundRoot, rel);
            try
            {
                byte[] bytes = File.ReadAllBytes(source);
                OggInfo info = OggInfo.Read(bytes);
                FileLicence licence = attributions.Of(rel);
                bool noLicence = SoundLicences.Unlicensed.TryGetValue("sound/" + rel, out string why);
                if (noLicence)
                    licence = new FileLicence("no licence: " + why, false, false, licence.Source);
                else if (SoundLicences.NonCommercialAtSource.TryGetValue("sound/" + rel, out string atSource))
                    licence = new FileLicence(atSource, true, false, licence.Source);
                string where = noLicence ? null : licence.NonCommercial ? (options.SkipNonCommercial ? null : "sound-nc") : "sound";
                var entry = new SoundIndexEntry
                {
                    Path = "sound/" + rel,
                    Ds = info.Deciseconds,
                    Rate = info.SampleRate,
                    Channels = info.Channels,
                    Licence = licence.Label,
                    Nc = licence.NonCommercial,
                    Unknown = licence.Unknown,
                    Attribution = licence.Source == null ? null : "sound/" + licence.Source,
                    Format = info.Format,
                    Bytes = bytes.Length,
                    Where = where,
                    File = where == null ? null : where + "/" + rel,
                };
                entries.Add(entry);
                totalBytes += bytes.Length;
                if (licence.NonCommercial)
                    ncBytes += bytes.Length;

                // The other place may hold a copy from an earlier run (the licence reading changed): remove it.
                DeleteIfExists(Path.Combine(licence.NonCommercial ? soundOut : ncOut, rel));
                if (noLicence)
                {
                    unlicensed++;
                    continue;
                }
                if (where == null)
                {
                    absent++;
                    continue;
                }
                string dest = Path.Combine(where == "sound" ? soundOut : ncOut, rel);
                if (IsUpToDate(dest, source, bytes.Length))
                {
                    upToDate++;
                    continue;
                }
                Directory.CreateDirectory(Path.GetDirectoryName(dest));
                File.WriteAllBytes(dest, bytes);
                File.SetLastWriteTimeUtc(dest, File.GetLastWriteTimeUtc(source));
                copied++;
            }
            catch (Exception e) when (e is InvalidDataException or IOException or UnauthorizedAccessException)
            {
                failed++;
                errors.WriteLine($"Anomaly.Tools.Sounds: sound/{rel}: {e.Message}");
            }
        }

        // D345: tg's licence notes go beside the sounds at the same paths, so a build names each sound's authors (CC BY asks for it)
        foreach (string note in Directory.EnumerateFiles(soundRoot, "*.txt", SearchOption.AllDirectories))
        {
            if (Attributions.IsLicenceNote(Path.GetFileName(note)))
                WriteIfChanged(Path.Combine(soundOut, Path.GetRelativePath(soundRoot, note)), File.ReadAllBytes(note));
        }

        // D344: a copy of a file with no licence from an earlier run goes (also tg's title1.mod, whose render DV240 once copied)
        foreach (string path in SoundLicences.Unlicensed.Keys)
            DeleteIfExists(Path.Combine(options.OutputDirectory, path));

        // D308: the TTS server's own sounds (the radio's clicks, the silicon voice's impulses), which the client's text to speech uses
        string ttsSource = Path.Combine(options.TgRoot, "tools", "tts", "tts-api");
        if (Directory.Exists(ttsSource))
        {
            string ttsOut = Path.Combine(options.OutputDirectory, "tts");
            Directory.CreateDirectory(ttsOut);
            foreach (string wav in Directory.EnumerateFiles(ttsSource, "*.wav"))
                WriteIfChanged(Path.Combine(ttsOut, Path.GetFileName(wav)), File.ReadAllBytes(wav));
        }

        WriteIfChanged(Path.Combine(soundOut, "index.json"), Encoding.UTF8.GetBytes(WriteIndex(entries)));
        List<SoundIndexEntry> ncFiles = entries.Where(e => e.Nc).ToList();
        if (options.SkipNonCommercial)
        {
            if (Directory.Exists(ncOut))
                Directory.Delete(ncOut, true);
        }
        else if (ncFiles.Count > 0)
        {
            Directory.CreateDirectory(ncOut);
            WriteIfChanged(Path.Combine(ncOut, "NOTICE.txt"), Encoding.UTF8.GetBytes(Notice(ncFiles)));
        }
        else if (Directory.Exists(ncOut))
        {
            Directory.Delete(ncOut, true);
        }

        Report(options, output, entries, otherExtensions, attributions, copied, upToDate, absent, unlicensed, failed, totalBytes, ncBytes);
        return failed == 0 ? 0 : 1;
    }

    /// <summary>The index file's text: a header line, then one entry per line (stable order, so a rerun changes nothing).</summary>
    public static string WriteIndex(IReadOnlyList<SoundIndexEntry> entries)
    {
        var sb = new StringBuilder();
        sb.Append("{\"version\":1,\"defaultLicence\":").Append(JsonSerializer.Serialize(Licences.Default))
            .Append(",\"files\":[\n");
        for (int i = 0; i < entries.Count; i++)
            sb.Append(JsonSerializer.Serialize(entries[i], JsonOptions)).Append(i + 1 < entries.Count ? ",\n" : "\n");
        sb.Append("]}\n");
        return sb.ToString();
    }

    private static string Notice(IReadOnlyList<SoundIndexEntry> ncFiles)
    {
        var sb = new StringBuilder();
        sb.Append("These sounds come from the tgstation repository (https://github.com/tgstation/tgstation). Their attribution files\n");
        sb.Append("(or, for a few, their source pages, D344) name a NON-COMMERCIAL licence (CC BY-NC or similar), which is not compatible\n");
        sb.Append("with the project's share-alike licence regime or with commercial use. They are kept apart from sound/ on purpose\n");
        sb.Append("(D35: a label, not a block). A free build ships them; ANOMALY_SKIP_NC=1 leaves them out (godot/tools/export-common.sh, D345).\n\n");
        sb.Append("Files (tg path: licence; attribution file):\n");
        foreach (SoundIndexEntry e in ncFiles)
            sb.Append(e.Path).Append(": ").Append(e.Licence).Append("; ").Append(e.Attribution ?? "?").Append('\n');
        return sb.ToString();
    }

    private static void Report(SoundToolOptions options, TextWriter output, List<SoundIndexEntry> entries,
        SortedDictionary<string, int> otherExtensions, Attributions attributions, int copied, int upToDate, int absent, int unlicensed, int failed,
        long totalBytes, long ncBytes)
    {
        output.WriteLine($"Anomaly.Tools.Sounds: {entries.Count} sound files ({totalBytes / 1048576.0:F1} MB) indexed in {Path.Combine(options.OutputDirectory, "sound", "index.json")}");
        output.WriteLine($"  copied {copied}, already up to date {upToDate}, absent (non-commercial, --skip-nc) {absent}, not copied (no licence, D344) {unlicensed}, failed {failed}");
        output.WriteLine("  skipped by extension: " + (otherExtensions.Count == 0
            ? "none"
            : string.Join(", ", otherExtensions.Select(kv => $"{kv.Key} {kv.Value}"))) + " (only .ogg and .mp3 are copied)");
        output.WriteLine("  licences:");
        foreach (var group in entries.GroupBy(e => e.Licence).OrderByDescending(g => g.Count()).ThenBy(g => g.Key, StringComparer.Ordinal))
        {
            if (group.Count() > 0 && !group.First().Unknown)
                output.WriteLine($"    {group.Count(),5}  {group.Key}");
        }

        List<SoundIndexEntry> nc = entries.Where(e => e.Nc).ToList();
        output.WriteLine($"  non-commercial files: {nc.Count} ({ncBytes / 1048576.0:F1} MB), " + (options.SkipNonCommercial ? "not copied (--skip-nc)" : "in sound-nc/ with a NOTICE"));
        foreach (SoundIndexEntry e in nc)
            output.WriteLine($"    {e.Path}: {e.Licence} ({e.Attribution})");

        List<SoundIndexEntry> notOgg = entries.Where(e => e.Format != "ogg").ToList();
        if (notOgg.Count > 0)
        {
            output.WriteLine($"  files named .ogg that are not Ogg Vorbis (copied as they are, indexed with format wav): {notOgg.Count}");
            foreach (SoundIndexEntry e in notOgg)
                output.WriteLine($"    {e.Path}: {e.Format}, {e.Rate} Hz, {e.Channels} ch, {e.Ds / 10:F2} s");
        }

        List<SoundIndexEntry> unknown = entries.Where(e => e.Unknown).ToList();
        output.WriteLine($"  files with unknown licence (named in an attribution file, no licence stated): {unknown.Count}");
        foreach (SoundIndexEntry e in unknown)
            output.WriteLine($"    {e.Path} ({e.Attribution})");

        if (attributions.Warnings.Count > 0)
        {
            output.WriteLine($"  warnings: {attributions.Warnings.Count}");
            foreach (string w in attributions.Warnings)
                output.WriteLine("    " + w);
        }
    }

    private static bool IsUpToDate(string dest, string source, long length)
    {
        var info = new FileInfo(dest);
        if (!info.Exists || info.Length != length)
            return false;
        // Some file systems keep only whole seconds (FAT keeps two): a copy within two seconds of the source counts as the same time.
        return Math.Abs((info.LastWriteTimeUtc - File.GetLastWriteTimeUtc(source)).TotalSeconds) <= 2;
    }

    private static void DeleteIfExists(string path)
    {
        if (File.Exists(path))
            File.Delete(path);
    }

    private static void WriteIfChanged(string path, byte[] bytes)
    {
        Directory.CreateDirectory(Path.GetDirectoryName(path));
        if (File.Exists(path) && new FileInfo(path).Length == bytes.Length && File.ReadAllBytes(path).AsSpan().SequenceEqual(bytes))
            return;
        File.WriteAllBytes(path, bytes);
    }

    /// <summary>Keeps one paragraph about the sounds at the end of SOURCE.txt (the icon tool writes the rest and keeps this paragraph).</summary>
    private static void WriteSourceNote(string path)
    {
        string existing = File.Exists(path) ? File.ReadAllText(path) : "";
        int at = existing.IndexOf(SourceMarker, StringComparison.Ordinal);
        string head = at >= 0 ? existing.Substring(0, at) : existing;
        if (head.Length > 0 && !head.EndsWith("\n\n", StringComparison.Ordinal))
            head += head.EndsWith('\n') ? "\n" : "\n\n";
        string note = SourceMarker + " from the tgstation sounds (https://github.com/tgstation/tgstation, sound/**/*.ogg),\n"
            + "copied unchanged to sound/ with the same paths as in tg. The tgstation README puts all assets, sound included, under\n"
            + "CC BY-SA 3.0 unless indicated otherwise; the attribution.txt files in tg's sound/ tree name other licences for some files.\n"
            + "sound/index.json holds each file's licence label (a label, not a block, D35). Files whose attribution names a\n"
            + "non-commercial licence are in sound-nc/ (see sound-nc/NOTICE.txt) or, with --skip-nc, absent; tg's licence notes (attribution,\n"
            + "credits, license .txt) are copied beside them. Files with no licence at all (D344) are indexed but not copied. Not committed.\n";
        WriteIfChanged(path, Encoding.UTF8.GetBytes(head + note));
    }
}
