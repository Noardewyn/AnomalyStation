using System.IO;
using System.Linq;
using System.Text;

namespace Anomaly.Tools.Icons;

// Owner: M2 P7. The conversion; the command line (IconToolOptions, Program.cs) is the M2 contracts step's.

/// <summary>
/// The conversion (M2 P7, D104, Q10): every <c>.dmi</c> under the tgstation clone's <c>icons/</c> becomes <c>&lt;icon path&gt;.png</c> (the
/// file's own bytes: a DMI is a PNG, and the extra zTXt chunk is ignored by every PNG reader) and <c>&lt;icon path&gt;.json</c> (states,
/// frame rectangles, directions, delays: <see cref="DmiJson"/>) under the output folder; every GAGS config becomes
/// <c>gags/&lt;config&gt;.json</c> (<see cref="GagsReader"/>). The output is derived from tg's art (CC BY-SA 3.0) and is git-ignored. Files that
/// are already up to date are not rewritten, so a second run is quick and changes nothing.
/// </summary>
public static class IconConverter
{
    /// <summary>Converts every icon and GAGS config of <paramref name="options"/>; returns the exit code (0: done, 1: some file failed, 2: the input is no tgstation clone).</summary>
    public static int Run(IconToolOptions options, TextWriter output, TextWriter errors)
    {
        string iconsRoot = Path.Combine(options.TgRoot, "icons");
        if (!Directory.Exists(iconsRoot))
        {
            errors.WriteLine($"Anomaly.Tools.Icons: {iconsRoot} does not exist (--tg must be a tgstation clone)");
            return 2;
        }

        Directory.CreateDirectory(options.OutputDirectory);
        // Godot must not import a thousand pictures: the client loads these files itself (godot/scripts/Render/IconPaths.cs).
        WriteIfChanged(Path.Combine(options.OutputDirectory, ".gdignore"), Array.Empty<byte>());
        string sourceNote = "Generated by tools/Anomaly.Tools.Icons from the tgstation icons (https://github.com/tgstation/tgstation), which are\n"
            + "licensed CC BY-SA 3.0 unless indicated otherwise (tgstation README). These files are derived works under the same\n"
            + "license. Not committed (D88's infrastructure pass decides how they ship).\n"
            + "\nFonts: copied unchanged to fonts/ from tgstation interface/fonts (the map's maptext fonts: Grand9K Pixel, Pixellari, TinyUnicode,\n"
            + "Spess Font, VCR OSD Mono; their licences are in fonts/license.txt). The client draws HUD maptext with them.\n"
            + "\nFont Awesome: copied unchanged to fonts/font-awesome/ from tgstation html/font-awesome (Font Awesome Free 6.7.2 by Fonticons, Inc.:\n"
            + "fonts SIL OFL 1.1, icons CC BY 4.0, code MIT; https://fontawesome.com/license/free). tgui's icons; the client draws them with it.\n";
        // tools/Anomaly.Tools.Sounds appends its own paragraph to this file (M4b): keep it.
        string sourcePath = Path.Combine(options.OutputDirectory, "SOURCE.txt");
        if (File.Exists(sourcePath))
        {
            string existing = File.ReadAllText(sourcePath);
            int sounds = existing.IndexOf("Sounds: generated by tools/Anomaly.Tools.Sounds", StringComparison.Ordinal);
            if (sounds >= 0)
                sourceNote += "\n" + existing.Substring(sounds);
        }
        WriteIfChanged(sourcePath, Encoding.UTF8.GetBytes(sourceNote));

        // Protocol version 18 (HUD maptext): the map's fonts, read by godot/scripts/Hud/Maptext/MaptextFonts.cs from fonts/.
        string fontsRoot = Path.Combine(options.TgRoot, "interface", "fonts");
        if (Directory.Exists(fontsRoot))
        {
            foreach (string font in Directory.EnumerateFiles(fontsRoot).Where(f => f.EndsWith(".ttf", StringComparison.OrdinalIgnoreCase) || Path.GetFileName(f) == "license.txt").OrderBy(f => f, StringComparer.Ordinal))
                WriteIfChanged(Path.Combine(options.OutputDirectory, "fonts", Path.GetFileName(font)), File.ReadAllBytes(font));
        }

        // M9 slice C: tgui's icon font (tg's html/font-awesome: the solid face and the stylesheet naming its icons), read by
        // godot/scripts/Hud/Tgui/FontAwesomeFont.cs from fonts/font-awesome/.
        string awesomeRoot = Path.Combine(options.TgRoot, "html", "font-awesome");
        foreach (string file in new[] { Path.Combine("webfonts", "fa-solid-900.ttf"), Path.Combine("css", "all.min.css") })
        {
            if (File.Exists(Path.Combine(awesomeRoot, file)))
                WriteIfChanged(Path.Combine(options.OutputDirectory, "fonts", "font-awesome", Path.GetFileName(file)), File.ReadAllBytes(Path.Combine(awesomeRoot, file)));
        }

        // M8z slice B (D236): the strip menu's slot pictures (tg's asset/simple/inventory, code/modules/asset_cache/assets/inventory.dm) are
        // plain PNGs, copied unchanged; the native StripMenu window draws them from icons/ui/inventory/.
        string inventoryRoot = Path.Combine(iconsRoot, "ui", "inventory");
        if (Directory.Exists(inventoryRoot))
        {
            foreach (string picture in Directory.EnumerateFiles(inventoryRoot, "*.png").OrderBy(f => f, StringComparer.Ordinal))
                WriteIfChanged(Path.Combine(options.OutputDirectory, "icons", "ui", "inventory", Path.GetFileName(picture)), File.ReadAllBytes(picture));
        }

        // Gaps package G1: the safe's dial (tg's asset/simple/safe, code/modules/asset_cache/assets/safe.dm) is a plain PNG, copied unchanged;
        // the native Safe window draws it from icons/ui/safe/.
        string dialPicture = Path.Combine(iconsRoot, "ui", "safe", "safe_dial.png");
        if (File.Exists(dialPicture))
            WriteIfChanged(Path.Combine(options.OutputDirectory, "icons", "ui", "safe", "safe_dial.png"), File.ReadAllBytes(dialPicture));

        // Syndicate N1b (D316): the NTOS radar's pictures (tg's asset/simple/radar_assets, code/modules/asset_cache/assets/radar.dm) are plain
        // PNGs, copied unchanged; the client's NtosRadar windows draw them from icons/ui/tgui/.
        foreach (string radarPicture in new[] { "ntosradar_background.png", "ntosradar_pointer.png", "ntosradar_pointer_S.png" })
        {
            string source = Path.Combine(iconsRoot, "ui", "tgui", radarPicture);
            if (File.Exists(source))
                WriteIfChanged(Path.Combine(options.OutputDirectory, "icons", "ui", "tgui", radarPicture), File.ReadAllBytes(source));
        }

        // The battle arcade's inn and campfire pictures (tg's asset/simple/arcade, code/modules/asset_cache/assets/arcade.dm) are plain PNGs,
        // copied unchanged beside the bosses' GIFs; the client's BattleArcade window draws them from icons/ui/arcade/.
        foreach (string arcadePicture in new[] { "shopkeeper.png", "fireplace.png" })
        {
            string source = Path.Combine(iconsRoot, "ui", "arcade", arcadePicture);
            if (File.Exists(source))
                WriteIfChanged(Path.Combine(options.OutputDirectory, "icons", "ui", "arcade", arcadePicture), File.ReadAllBytes(source));
        }

        // The exploration drones' adventure screens (tg's asset/simple/adventure, code/modules/asset_cache/assets/adventure.dm) are plain PNGs,
        // copied unchanged; the client's ExodroneConsole and AdventureBrowser windows draw them from icons/ui/adventure/.
        string adventureRoot = Path.Combine(iconsRoot, "ui", "adventure");
        if (Directory.Exists(adventureRoot))
        {
            foreach (string picture in Directory.EnumerateFiles(adventureRoot, "*.png").OrderBy(f => f, StringComparer.Ordinal))
                WriteIfChanged(Path.Combine(options.OutputDirectory, "icons", "ui", "adventure", Path.GetFileName(picture)), File.ReadAllBytes(picture));
        }

        // M10 slice F: the lobby menu's pictures (tg's asset/simple/namespaced/lobby_menu_icons, code/modules/asset_cache/assets/tgui.dm:75:
        // icons/hud/lobby/png/) are plain PNGs, some animated (APNG: the buttons' press and enable flicks), copied unchanged; the
        // client's lobby screen draws them from icons/hud/lobby/png/.
        string lobbyRoot = Path.Combine(iconsRoot, "hud", "lobby", "png");
        if (Directory.Exists(lobbyRoot))
        {
            foreach (string picture in Directory.EnumerateFiles(lobbyRoot, "*.png").OrderBy(f => f, StringComparer.Ordinal))
                WriteIfChanged(Path.Combine(options.OutputDirectory, "icons", "hud", "lobby", "png", Path.GetFileName(picture)), File.ReadAllBytes(picture));
        }

        int converted = 0, written = 0, failed = 0, states = 0;

        // M9 slice E: NtOS's header pictures (tg's /datum/asset/simple/headers, code/modules/asset_cache/assets/headers.dm) are GIFs:
        // each becomes <path without .gif>.png and .json like a .dmi (GifReader), so the client's icon library reads them by their tg path.
        // Gaps S4c (D327): the arcade's bosses (tg's /datum/asset/simple/arcade, code/modules/asset_cache/assets/arcade.dm) the same way.
        // Gaps P3: the DNA console's gene pictures (tg's /datum/asset/simple/genetics, code/modules/asset_cache/assets/genetics.dm).
        foreach (string gifFile in new[] { Path.Combine(iconsRoot, "ui", "programs"), Path.Combine(iconsRoot, "ui", "arcade"), Path.Combine(iconsRoot, "ui", "dna") }
            .Where(Directory.Exists).SelectMany(root => Directory.EnumerateFiles(root, "*.gif").OrderBy(f => f, StringComparer.Ordinal)))
        {
            {
                string relative = Path.GetRelativePath(options.TgRoot, gifFile).Replace('\\', '/');
                string stem = relative.Substring(0, relative.Length - ".gif".Length);
                try
                {
                    (byte[] png, DmiFile meta) = GifReader.ToSheet(File.ReadAllBytes(gifFile)); // tg's mafia.gif is a PNG: copied as it is
                    written += WriteIfChanged(Path.Combine(options.OutputDirectory, stem + ".png"), png) ? 1 : 0;
                    written += WriteIfChanged(Path.Combine(options.OutputDirectory, stem + ".json"), Encoding.UTF8.GetBytes(DmiJson.Write(meta))) ? 1 : 0;
                    converted++;
                    states++;
                }
                catch (Exception e) when (e is InvalidDataException or IOException or UnauthorizedAccessException or IndexOutOfRangeException)
                {
                    failed++;
                    errors.WriteLine($"Anomaly.Tools.Icons: {relative}: {e.Message}");
                }
            }
        }

        // The title's backdrop (tg's /turf/closed/indestructible/splashscreen, on CentCom, and /atom/movable/screen/splash) is the one atom icon
        // that is a plain PNG: a sheet of one unnamed state like a GIF's, so the client's icon library reads it by its tg path.
        string titlePicture = Path.Combine(iconsRoot, "blanks", "blank_title.png");
        if (File.Exists(titlePicture))
        {
            (byte[] png, DmiFile meta) = GifReader.ToSheet(File.ReadAllBytes(titlePicture));
            written += WriteIfChanged(Path.Combine(options.OutputDirectory, "icons", "blanks", "blank_title.png"), png) ? 1 : 0;
            written += WriteIfChanged(Path.Combine(options.OutputDirectory, "icons", "blanks", "blank_title.json"), Encoding.UTF8.GetBytes(DmiJson.Write(meta))) ? 1 : 0;
            converted++;
            states++;
        }

        var seen = new HashSet<string>(StringComparer.Ordinal);
        foreach (string file in Directory.EnumerateFiles(iconsRoot, "*.dmi", SearchOption.AllDirectories).OrderBy(f => f, StringComparer.Ordinal))
        {
            string relative = Path.GetRelativePath(options.TgRoot, file).Replace('\\', '/');
            string stem = relative.Substring(0, relative.Length - ".dmi".Length);
            try
            {
                byte[] bytes = File.ReadAllBytes(file);
                DmiFile dmi = DmiReader.Read(bytes);
                string json = DmiJson.Write(dmi);
                if (!seen.Add(stem))
                    throw new InvalidDataException("two icons convert to " + stem);
                written += WriteIfChanged(Path.Combine(options.OutputDirectory, stem + ".png"), bytes) ? 1 : 0;
                written += WriteIfChanged(Path.Combine(options.OutputDirectory, stem + ".json"), Encoding.UTF8.GetBytes(json)) ? 1 : 0;
                converted++;
                states += dmi.States.Count;
            }
            catch (Exception e) when (e is InvalidDataException or IOException or UnauthorizedAccessException or System.Text.Json.JsonException)
            {
                failed++;
                errors.WriteLine($"Anomaly.Tools.Icons: {relative}: {e.Message}");
            }
        }

        int gags = 0;
        var wroteTypes = new List<GagsType>();
        foreach (GagsType type in GagsReader.Read(options.TgRoot))
        {
            try
            {
                string json = GagsReader.Convert(options.TgRoot, type);
                written += WriteIfChanged(Path.Combine(options.OutputDirectory, "gags", GagsReader.FileOf(type.Path)), Encoding.UTF8.GetBytes(json)) ? 1 : 0;
                wroteTypes.Add(type);
                gags++;
            }
            catch (Exception e) when (e is InvalidDataException or IOException or UnauthorizedAccessException or System.Text.Json.JsonException)
            {
                failed++;
                errors.WriteLine($"Anomaly.Tools.Icons: {type.Path}: {e.Message}");
            }
        }
        written += WriteIfChanged(Path.Combine(options.OutputDirectory, "gags", "index.json"), Encoding.UTF8.GetBytes(GagsReader.WriteIndex(wroteTypes))) ? 1 : 0;

        output.WriteLine($"Anomaly.Tools.Icons: {converted} icons ({states} states) and {gags} GAGS configs converted into {options.OutputDirectory} ({written} files written, {failed} failed)");
        return failed == 0 ? 0 : 1;
    }

    /// <summary>Writes <paramref name="bytes"/> to <paramref name="path"/> (creating its folder) unless the file already holds them; true when it wrote.</summary>
    private static bool WriteIfChanged(string path, byte[] bytes)
    {
        Directory.CreateDirectory(Path.GetDirectoryName(path));
        if (File.Exists(path))
        {
            var info = new FileInfo(path);
            if (info.Length == bytes.Length && File.ReadAllBytes(path).AsSpan().SequenceEqual(bytes))
                return false;
        }
        File.WriteAllBytes(path, bytes);
        return true;
    }
}
