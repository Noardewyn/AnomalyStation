    // tg: code/modules/meteors/meteor_spawning.dm:7
    public static void spawn_meteor(DmList meteor_types = null, object direction = null, atom target = null, float distance_from_edge = 0)
    {
        if (Dm.truthy(SSmapping.is_planetary()))
        {
            stack_trace("Tried to spawn meteors in a map which isn't in space.", "code/modules/meteors/meteor_spawning.dm", 9);
            return; // We're not going to find any space turfs here
        }
        turf picked_start = null;
        turf picked_goal = null;
        int max_i = 10;//number of tries to spawn meteor.
        while (!isspaceturf(picked_start))
        {
            object start_side;
            if (Dm.truthy(direction)) //If a direction has been specified, we set start_side to it. Otherwise, pick randomly
                start_side = direction;
            else
                start_side = pick(GLOB.cardinals);
            object start_Z = pick(SSmapping.levels_by_trait(ZTRAIT_STATION));
            picked_start = spaceDebrisStartLoc(start_side, start_Z, distance_from_edge);
            if (target != null)
            {
                if (!isturf(target))
                    target = get_turf(target);
                picked_goal = (turf)target;
            }
            else
                picked_goal = spaceDebrisFinishLoc(start_side, start_Z);
            max_i--;
            if (max_i <= 0)
                return;
        }
        object new_meteor = pick_weight(meteor_types);
        Dm.@new((Type)new_meteor, picked_start, picked_goal);
    }

    // tg: code/modules/meteors/meteor_spawning.dm:56
    public static turf spaceDebrisFinishLoc(object startSide = null, object Z = null)
    {
        float pad = TRANSITIONEDGE + obj_effect_meteor.MAP_EDGE_PAD;
        float side = Dm.num(startSide), maxx = Dm.world.maxx, maxy = Dm.world.maxy;
        float endy = 0, endx = 0;
        if (side == NORTH)
        {
            endy = pad;
            endx = rand(pad, maxx - pad);
        }
        else if (side == EAST)
        {
            endy = rand(pad, maxy - pad);
            endx = pad;
        }
        else if (side == SOUTH)
        {
            endy = maxy - pad;
            endx = rand(pad, maxx - pad);
        }
        else if (side == WEST)
        {
            endy = rand(pad, maxy - pad);
            endx = maxx - pad;
        }
        return locate(endx, endy, Dm.num(Z));
    }

    /**
     * Receives a mob candidate, transforms them into a changeling, and hurls them at the station inside of a changeling meteor
     *
     * Takes a given candidate and turns them into a changeling, generates a changeling meteor, and throws it at the station.
     * Returns the changeling generated by the event, NOT the meteor. This is so that it plays nicely with the dynamic ruleset
     * while still being usable in the ghost_role event as well.
     *
     * Arguments:
     * * candidate - The mob (player) to be transformed into a changeling and meteored.
     */
    // tg: code/modules/meteors/meteor_spawning.dm:80
    public static async DmTask<object> generate_changeling_meteor(datum_mind player_mind = null)
    {
        turf picked_start = null;

        if (Dm.truthy(SSmapping.is_planetary()))
        {
            DmList possible_start = Dm.list();
            foreach (obj_effect_landmark_carpspawn spawn_point in Dm.each<obj_effect_landmark_carpspawn>(GLOB.landmarks_list))
                Dm.append(ref possible_start, get_turf(spawn_point));
            picked_start = pick(possible_start) as turf;
        }
        else
        {
            object start_z = pick(SSmapping.levels_by_trait(ZTRAIT_STATION) as DmList);
            object start_side = pick(GLOB.cardinals);
            picked_start = spaceDebrisStartLoc(start_side, start_z);
        }

        if (picked_start == null)
            stack_trace("No valid spawn location for changeling meteor", "code/modules/meteors/meteor_spawning.dm", 93);

        obj_effect_meteor_meaty_changeling changeling_meteor = Dm.@new<obj_effect_meteor_meaty_changeling>(picked_start, get_random_station_turf());
        mob_living_carbon_human new_changeling = Dm.@new<mob_living_carbon_human>(picked_start);

        await new_changeling.forceMove(changeling_meteor); //Place our payload inside of its vessel

        await player_mind.transfer_to(new_changeling, force_key_move: TRUE);
        await player_mind.add_antag_datum(typeof(datum_antagonist_changeling_space));
        Dm.output_to(new_changeling, sound(Dm.resource("sound/effects/magic/mutate.ogg"))); // SEND_SOUND (DIRECT_OUTPUT, rules 12)
        message_admins(Dm.text("[] has been made into a space changeling by an event.", ADMIN_LOOKUPFLW(new_changeling)));
        new_changeling.log_message("was spawned as a midround space changeling by an event.", LOG_GAME);

        datum_antagonist_changeling changeling_datum = Dm.locate<datum_antagonist_changeling>(player_mind.antag_datums);
        await changeling_datum.give_power(typeof(datum_action_changeling_void_adaption));
        await changeling_datum.give_power(typeof(datum_action_changeling_weapon_arm_blade));
        await new_changeling.equipOutfit(typeof(datum_outfit_changeling_space));

        return new_changeling;
    }
