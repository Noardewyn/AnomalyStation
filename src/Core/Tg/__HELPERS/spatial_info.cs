        DmList dot = null;
        turf center_turf = get_turf(source);
        if (!Dm.truthy(center_turf))
            return dot;

        dot = Dm.list();

        if (Dm.le(view_radius, 0))//special case for if only source cares
        {
            foreach (atom_movable target in Dm.each_cast<atom_movable>(center_turf))
            {
                DmList recursive_contents = target.important_recursive_contents?[contents_type] as DmList;
                if (Dm.truthy(recursive_contents))
