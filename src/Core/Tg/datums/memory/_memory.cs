    // tg: code/datums/memory/_memory.dm:114
    public virtual void select_mood_verb(object story_mood = null)
    {
        if (Dm.eq(story_mood, MOODLESS_MEMORY))
        {
            // The protagonist didn't end up having a mood, so just continue on
            memory_flags = Dm.bitor(memory_flags, MEMORY_FLAG_NOMOOD);
            return;
        }

        object possible_verbs = null;
        float mood = Dm.num(story_mood);
        // switch(story_mood): the first range that holds it (rules 6.7)
        if (mood >= MOOD_SAD4 && mood <= MOOD_SAD2)
            possible_verbs = get_sad_moods();
        else if (mood >= MOOD_SAD2 && mood <= MOOD_HAPPY2)
            possible_verbs = get_neutral_moods();
        else if (mood >= MOOD_HAPPY2 && mood <= MOOD_HAPPY4)
            possible_verbs = get_happy_moods();

        if (!Dm.truthy(length(possible_verbs)))
            return;

        mood_verb = pick(possible_verbs);
    }

