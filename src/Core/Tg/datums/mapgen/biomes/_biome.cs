///This datum handles the transitioning from a turf to a specific biome, and handles spawning decorative structures and mobs.
// tg: code/datums/mapgen/biomes/_biome.dm:7
public partial class datum_biome : datum
{
    private const string CAVE_SPAWN_MOB = "mob";
    private const string CAVE_SPAWN_FEATURE = "feature";
    private const string CAVE_SPAWN_TENDRIL = "tendril";
    private const string CAVE_SPAWN_MEGAFAUNA = "megafauna";

    // tg: code/datums/mapgen/biomes/_biome.dm:39
    public override async DmTask New(params object[] __extra)
    {
        await base.New(__extra);
        if (Dm.truthy(length(flora_types)))
            flora_types = expand_weights(fill_with_ones(flora_types) as DmList) as DmList;

        if (Dm.truthy(length(fauna_types)))
            fauna_types = expand_weights(fill_with_ones(fauna_types) as DmList) as DmList;

        if (Dm.truthy(length(feature_types)))
            feature_types = expand_weights(feature_types) as DmList;

        if (megafauna_types == null)
            megafauna_types = GLOB.megafauna_spawn_list;
    }

    ///This proc handles the creation of a turf of a specific biome type
    // tg: code/datums/mapgen/biomes/_biome.dm:54
    public virtual async DmTask generate_turf(turf gen_turf = null, object closed = null)
    {
        if (Dm.truthy(closed))
        {
            await gen_turf.ChangeTurf(closed_turf_type, null, CHANGETURF_DEFER_CHANGE);
            return;
        }

        await gen_turf.ChangeTurf(open_turf_type, null, CHANGETURF_DEFER_CHANGE);

        if (Dm.truthy(length(flora_types)) && Dm.prob(flora_density))
        {
            object flora = pick(flora_types);
            Dm.@new((Type)flora, gen_turf);
            return;
        }

        if (Dm.truthy(length(feature_types)) && Dm.prob(feature_density))
        {
            object picked_feature = pick(feature_types);
            Dm.@new((Type)picked_feature, gen_turf);
            return;
        }

        if (Dm.truthy(length(fauna_types)) && Dm.prob(fauna_density))
        {
            object fauna = pick(fauna_types);
            Dm.@new((Type)fauna, gen_turf);
        }
    }

    /// This proc handles the creation of a turf of a specific biome type, assuming
    /// that the turf has not been initialized yet. Don't call this unless you know
    /// what you're doing.
    // tg: code/datums/mapgen/biomes/_biome.dm:79
    public virtual turf generate_turf_for_terrain(turf gen_turf = null, object closed = null)
    {
        Type turf_type = Dm.truthy(closed) ? closed_turf_type : open_turf_type;
        var new_turf = (turf)Dm.@new(turf_type, gen_turf);
        return new_turf;
    }

    /**
     * This proc handles the sequential creation of turfs of a specific biome type
     * in order to optimize the generation for large amount of turfs.
     *
     * Arguments:
     * * gen_turfs - List of turfs to use for turf generation.
     *
     * Returns a new list of turfs that were generated by the biome.
     */
    // tg: code/datums/mapgen/biomes/_biome.dm:94
    public virtual async DmTask<DmList> generate_turfs_for_terrain(DmList gen_turfs = null)
    {
        DmList new_turfs = Dm.list();

        foreach (turf gen_turf in Dm.each<turf>(gen_turfs))
        {
            object closed = gen_turfs[gen_turf];
            Type turf_type = Dm.truthy(closed) ? closed_turf_type : open_turf_type;
            var new_turf = (turf)Dm.@new(turf_type, gen_turf);
            new_turfs[new_turf] = turf_type;

            if (Dm.truthy(Dm.bitand(gen_turf.turf_flags, NO_RUINS)))
                new_turf.turf_flags = Dm.bitor(new_turf.turf_flags, NO_RUINS);

            // CHECK_TICK (__DEFINES/_tick.dm:21), awaited in a suspending proc
            if (TICK_CHECK())
                await stoplag();
        }

        return new_turfs;
    }

    /**
     * This proc handles populating the given turfs based on whether flora, features
     * and fauna are allowed. Does not take megafauna into account.
     *
     * Does nothing if `flora_allowed`, `features_allowed` and `fauna_allowed` are
     * `FALSE`, or if there's no flora, feature or fauna types for the matching
     * allowed type. Aka, we return early if the proc wouldn't do anything anyway.
     */
    // tg: code/datums/mapgen/biomes/_biome.dm:119
    public virtual async DmTask populate_turfs(DmList target_turfs = null, object flora_allowed = null, object features_allowed = null, object fauna_allowed = null)
    {
        bool has_flora = Dm.truthy(flora_allowed) && Dm.truthy(length(flora_types));
        bool has_features = Dm.truthy(features_allowed) && Dm.truthy(length(feature_types));
        bool has_fauna = Dm.truthy(fauna_allowed) && Dm.truthy(length(fauna_types));

        if (!has_flora && !has_features && !has_fauna)
            return;

        // Assoc list of spawned categories to
        // Static as to be shared between all biomes
        TgState state = TgState.Current;
        state.datum_biome_populate_turfs__spawn_data ??= Dm.list(
            Dm.kv(CAVE_SPAWN_FEATURE, Dm.list()),
            Dm.kv(CAVE_SPAWN_TENDRIL, Dm.list()),
            Dm.kv(CAVE_SPAWN_MOB, Dm.list()),
            Dm.kv(CAVE_SPAWN_MEGAFAUNA, Dm.list()));
        DmList spawn_data = state.datum_biome_populate_turfs__spawn_data;

        foreach (turf generated_turf in Dm.each<turf>(target_turfs))
        {
            // TURF-IDENTITY: the generator's list holds the turfs as generated; tg's references name their cells, so a river spawn_rivers
            // put there since (ChangeTurf's CHANGETURF_SKIP) is what tg sees, and skips below
            var target_turf = (turf)turf.dm_identity(generated_turf);
            // Only put stuff on open turfs we generated, so closed walls and rivers and stuff are skipped
            if (!istype(target_turf, open_turf_type))
                continue;

            // CHECK_TICK (__DEFINES/_tick.dm:21), awaited in a suspending proc
            if (TICK_CHECK())
                await stoplag();
            if (!Dm.truthy(Dm.bitand(target_turf.turf_flags, TURF_BLOCKS_POPULATE_TERRAIN_FLORAFEATURES)))
            {
                if (Dm.truthy(flora_allowed) && Dm.prob(flora_density))
                {
                    object flora_type = pick(flora_types);
                    Dm.@new((Type)flora_type, target_turf);
                    continue;
                }

                if (Dm.truthy(features_allowed) && Dm.prob(feature_density))
                {
                    bool can_spawn_feature = true;
                    foreach (turf spawn_turf in Dm.each<turf>(spawn_data[CAVE_SPAWN_FEATURE]))
                    {
                        if (get_dist(spawn_turf, target_turf) <= feature_exclusion_radius)
                        {
                            can_spawn_feature = false;
                            break;
                        }
                    }

                    if (can_spawn_feature)
                    {
                        object picked_feature = pick(feature_types);
                        Dm.@new((Type)picked_feature, target_turf);
                        Dm.append((DmList)spawn_data[CAVE_SPAWN_FEATURE], target_turf);
                        continue;
                    }
                }
            }

            if (!Dm.truthy(fauna_allowed) || !Dm.prob(fauna_density))
                continue;

            object picked_mob = pick(fauna_types);
            bool is_megafauna = false;
            bool is_tendril = false;

            if (Dm.eq(picked_mob, SPAWN_MEGAFAUNA))
            {
                picked_mob = pick_weight(megafauna_types);
                is_megafauna = true;
            }
            else
            {
                is_tendril = ispath(picked_mob, typeof(mob_living_basic_mining_tendril));
            }

            bool can_spawn = true;
            if (is_tendril)
            {
                foreach (turf spawn_turf in Dm.each<turf>(spawn_data[CAVE_SPAWN_TENDRIL]))
                {
                    if (get_dist(spawn_turf, target_turf) <= tendril_exclusion_radius)
                    {
                        can_spawn = false;
                        break;
                    }
                }

                if (!can_spawn)
                    continue;

                // Also avoid spawning them next to megafauna
                foreach (turf spawn_turf in Dm.each<turf>(spawn_data[CAVE_SPAWN_MEGAFAUNA]))
                {
                    if (get_dist(spawn_turf, target_turf) <= megafauna_exclusion_radius)
                    {
                        can_spawn = false;
                        break;
                    }
                }
            }
            else if (is_megafauna)
            {
                // Megafauna can spawn wherever it wants as long as its not next to another mega
                foreach (turf spawn_turf in Dm.each<turf>(spawn_data[CAVE_SPAWN_MEGAFAUNA]))
                {
                    if (get_dist(spawn_turf, target_turf) <= megafauna_exclusion_radius)
                    {
                        can_spawn = false;
                        break;
                    }
                }
            }
            else
            {
                foreach (turf spawn_turf in Dm.each<turf>(spawn_data[CAVE_SPAWN_MOB]))
                {
                    if (get_dist(spawn_turf, target_turf) <= mob_exclusion_radius)
                    {
                        can_spawn = false;
                        break;
                    }
                }
            }

            if (!can_spawn)
                continue;

            if (is_tendril)
                Dm.append((DmList)spawn_data[CAVE_SPAWN_TENDRIL], target_turf);
            else if (is_megafauna)
                Dm.append((DmList)spawn_data[CAVE_SPAWN_MEGAFAUNA], target_turf);
            Dm.append((DmList)spawn_data[CAVE_SPAWN_MOB], target_turf);

            Dm.@new((Type)picked_mob, target_turf);

            // the mining mob respawner (game/objects/effects/mining_mob_respawner.dm), which respawns them in ash storms, comes with the fauna (D304 L5)
            if (!is_tendril && !is_megafauna)
                Dm.Deferred("code/datums/mapgen/biomes/_biome.dm:216", "populate_turfs: the mining mob respawner comes with the fauna and the ash storms (D304 L4, L5)");

            // There can be only one Bubblegum, so don't waste spawns on it
            if (ispath(picked_mob, typeof(mob_living_simple_animal_hostile_megafauna_bubblegum)))
                megafauna_types.Remove(picked_mob);
        }
    }
}

