"""Writes the catalog entries of the machine and furniture waves into godot/assets/models/models.json.

Each wave model's glTF clips say which mesh nodes a source state shows (constant scale keys) and which ones move (a hatch's
rotation, a drawer's slide). SPECS (catalog_wave_specs.py) maps each clip to tg's condition: an icon state ("s:"), an overlay
("o:"), the open channel of the entry ("open": a pivoted part swings or slides while tg shows it open), or nothing.
Run from the repository root: python tools/art/catalog_waves.py
"""
import json, math, re, struct, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
MODELS = ROOT / 'godot/assets/models'
CATALOG = MODELS / 'models.json'
MARKER = '      // Generated by tools/art/catalog_waves.py from catalog_wave_specs.py: edit the specs and run it again, not the entries below.'
sys.path.insert(0, str(Path(__file__).parent))
from catalog_wave_specs import SPECS  # noqa: E402

HIDDEN = 1e-3  # a rest or key scale under it hides the node (the wave models use 0, the required models 1e-5; GlbReader.HiddenScale)


def load_glb(path):
    b = path.read_bytes()
    n = struct.unpack('<I', b[12:16])[0]
    g = json.loads(b[20:20 + n])
    o = 20 + n
    return g, b[o + 8:o + 8 + struct.unpack('<I', b[o:o + 4])[0]]


def accessor(g, binc, i):
    a = g['accessors'][i]
    bv = g['bufferViews'][a['bufferView']]
    k = {'SCALAR': 1, 'VEC2': 2, 'VEC3': 3, 'VEC4': 4}[a['type']]
    o = bv.get('byteOffset', 0) + a.get('byteOffset', 0)
    stride = bv.get('byteStride', 4 * k)
    return [struct.unpack_from('<%df' % k, binc, o + j * stride) for j in range(a['count'])]


def qmul(a, b):
    ax, ay, az, aw = a
    bx, by, bz, bw = b
    return (aw * bx + ax * bw + ay * bz - az * by, aw * by - ax * bz + ay * bw + az * bx,
            aw * bz + ax * by - ay * bx + az * bw, aw * bw - ax * bx - ay * by - az * bz)


def swing(q0, q1):
    """Axis (glTF/Godot, rounded) and degrees that take q0 to q1."""
    d = qmul(q1, (-q0[0], -q0[1], -q0[2], q0[3]))
    if d[3] < 0:
        d = tuple(-x for x in d)
    s = math.sqrt(max(0.0, 1 - d[3] * d[3]))
    deg = math.degrees(2 * math.acos(max(-1.0, min(1.0, d[3]))))
    if s < 1e-6 or deg < 0.5:
        return None, 0.0
    return [round(x / s, 4) + 0.0 for x in d[:3]], round(deg, 2)


class Glb:
    def __init__(self, rel):
        self.rel = rel
        g, binc = load_glb(MODELS / rel)
        self.nodes = g['nodes']
        self.mesh_nodes = list(dict.fromkeys(n['name'] for n in self.nodes if 'mesh' in n))  # one part per name: the loader takes every node of it
        self.hidden = {n['name'] for n in self.nodes if 'mesh' in n and abs(n.get('scale', [1, 1, 1])[0]) < HIDDEN}
        self.clips = {}
        self.carried = {}  # mesh node -> its carrier's origin, for a node that moves with an empty one and is not on its origin
        for a in g.get('animations', []):
            clip = {}
            for ch in a['channels']:
                s = a['samplers'][ch['sampler']]
                clip.setdefault(self.nodes[ch['target']['node']]['name'], {})[ch['target']['path']] = (
                    [t[0] for t in accessor(g, binc, s['input'])], accessor(g, binc, s['output']))
            self.clips[a['name']] = clip

    def shown(self, clip):
        """Nodes a clip shows (steady or blinking) and those it hides."""
        show, hide = set(), set()
        for node, ch in self.clips[clip].items():
            if 'scale' in ch:
                xs = [v[0] for v in ch['scale'][1]]
                (show if max(abs(x) for x in xs) >= HIDDEN else hide).add(node)
        return show, hide

    def motion(self, clip):
        """node -> (axis, degrees, move) of a clip's first key to its farthest (its last, or the open pose of a clip that opens and closes again)."""
        out = {}
        rest = {n['name']: n for n in self.nodes}
        for node, ch in self.clips[clip].items():
            axis, deg, move = None, 0.0, None
            # a clip that only holds one pose (the required models' cover_open) is measured from the node's rest pose
            def keys(path, default):
                v = ch[path][1]
                return [tuple(rest[node].get(path, default))] + v if all(q == v[0] for q in v) else v
            if 'rotation' in ch:
                v = keys('rotation', [0, 0, 0, 1])
                axis, deg = max((swing(v[0], q) for q in v), key=lambda s: s[1])
            if 'translation' in ch:
                v = keys('translation', [0, 0, 0])
                far = max(v, key=lambda q: sum((x - y) ** 2 for x, y in zip(q, v[0])))
                d = [round(b - a, 4) + 0.0 for a, b in zip(v[0], far)]
                if any(abs(x) > 1e-3 for x in d):
                    move = d
            if axis or move:
                out[node] = (axis, deg, move)
        # a mesh node the clip leaves still moves with the empty node that carries it (a cover on its hinge); its origin must be the carrier's to turn about it
        parent = {c: i for i, n in enumerate(self.nodes) for c in n.get('children', [])}
        for i, n in enumerate(self.nodes):
            if 'mesh' not in n or n['name'] in out:
                continue
            j = parent.get(i)
            while j is not None and self.nodes[j]['name'] not in out:
                j = parent.get(j)
            if j is not None and 'mesh' not in self.nodes[j]:
                out[n['name']] = out[self.nodes[j]['name']]
                if any(abs(x) > 1e-4 for x in n.get('translation', [0, 0, 0])):
                    self.carried[n['name']] = self.origin(j)  # it turns about its carrier's origin, not its own (pivotAt)
        return out

    def origin(self, i):
        """A node's origin in the file's space (its rest pose)."""
        parent = {c: k for k, n in enumerate(self.nodes) for c in n.get('children', [])}
        p = [0.0, 0.0, 0.0]
        while i is not None:
            n = self.nodes[i]
            s, q = n.get('scale', [1, 1, 1]), n.get('rotation', [0, 0, 0, 1])
            v = qmul(qmul(q, (p[0] * s[0], p[1] * s[1], p[2] * s[2], 0.0)), (-q[0], -q[1], -q[2], q[3]))
            p = [v[k] + n.get('translation', [0, 0, 0])[k] for k in range(3)]
            i = parent.get(i)
        return [round(x, 4) + 0.0 for x in p]

    def squeeze(self, clip):
        """node -> its farthest scale's ratio to its first key, for a node a clip squeezes; a scale to or from zero shows or hides it instead."""
        out = {}
        for node, ch in self.clips[clip].items():
            if 'scale' in ch:
                v = ch['scale'][1]
                if any(x == 0 for q in v for x in q):
                    continue
                far = max(v, key=lambda q: sum((x - y) ** 2 for x, y in zip(q, v[0])))
                r = [round(b / a, 4) for a, b in zip(v[0], far)]
                if any(abs(x - 1) > 1e-3 for x in r):
                    out[node] = r
        return out

    def flick_motion(self, clip):
        """mesh node -> {flickMove, flickDegrees, flickScale} of a clip that plays while tg flicks a state: a node's own motion, or the move of the empty
        node that carries it (a mass driver's carriage), and a scale's farthest ratio to its first key (its actuator squeezed)."""
        parent = {c: i for i, n in enumerate(self.nodes) for c in n.get('children', [])}
        names = {n['name']: i for i, n in enumerate(self.nodes)}
        moved = {}
        for node, (axis, deg, move) in self.motion(clip).items():
            moved[node] = dict({'axis': axis, 'flickDegrees': deg} if axis else {}, **({'flickMove': move} if move else {}))
        for node, ch in self.clips[clip].items():
            if 'scale' in ch:
                v = ch['scale'][1]
                far = max(v, key=lambda q: sum((x - y) ** 2 for x, y in zip(q, v[0])))
                moved.setdefault(node, {})['flickScale'] = [round(b / a, 4) for a, b in zip(v[0], far)]
        out = {}
        for name in self.mesh_nodes:
            i, own = names[name], {}
            while i is not None:
                own = dict(moved.get(self.nodes[i]['name'], {}), **own)
                i = parent.get(i)
            if own:
                out[name] = own
        return out

    def peak(self, clip):
        """Seconds from a clip's start to its farthest pose."""
        best = (0.0, 0.0)
        for ch in self.clips[clip].values():
            for path, (times, values) in ch.items():
                d = [sum((x - y) ** 2 for x, y in zip(q, values[0])) for q in values]
                j = max(range(len(d)), key=d.__getitem__)
                best = max(best, (d[j], times[j] - times[0]))
        return round(best[1], 2)

    def seconds(self, clip):
        return round(max(max(t for t in ch[p][0]) for ch in self.clips[clip].values() for p in ch), 2)


def cond(c):
    """'s:state' / 'o:overlay' / '!o:overlay' / '!s:state' -> (key, value)."""
    neg = c.startswith('!')
    kind, value = c.lstrip('!').split(':', 1)
    key = {'s': 'states', 'o': 'overlays'}[kind]
    return ('except' + key[0].upper() + key[1:] if neg else key), value


def entry(spec):
    if 'entry' in spec:
        return spec['entry']  # written out whole: a model exported as one file per state
    if spec.get('hidden'):
        return {'id': spec['id'], 'hidden': True, 'icons': spec['icons'], 'states': spec['states'], 'rule': 'single', 'texture': 'model',
                'source': {'width': 2.0, 'height': 2.0}, 'fit': {'width': 'tile', 'height': 2.0}, 'parts': {}}
    glb = Glb(spec['glb'])
    clips = spec.get('clips', {})
    clips = {c: w for c, w in clips.items() if w is not None or c in glb.clips}  # an unused clip a family's helper names may be absent
    for c in clips:
        if c not in glb.clips:
            raise SystemExit(f"{spec['id']}: {spec['glb']} has no clip '{c}' (has {list(glb.clips)})")
    shows = {}      # node -> {key: [values]} of the choice clips that show it
    touched = set()  # nodes some mapped choice clip shows or hides
    moves, hides, flicks, opens = {}, {}, {}, {}  # opens: node -> its scale ratio when open (a shutter rolled up)
    open_clip = None
    for clip, what in clips.items():
        if what is None:
            continue
        if isinstance(what, str) and what.startswith('flick '):
            # tg flicks a state: the clip's moving nodes go to their farthest pose on the flick's frames the spec's pose list marks (all of them without one)
            # and back, at the pace of the clip's way out
            states = what[6:].split('|')
            for node, m in glb.flick_motion(clip).items():
                f = {'states': states, 'seconds': glb.peak(clip)}
                if clip in spec.get('flickPose', {}):
                    f['frames'] = spec['flickPose'][clip]
                f.update({k: v for k, v in m.items() if k != 'axis'})
                flicks[node] = (m.get('axis'), f)
            continue
        if what == 'open' or isinstance(what, str) and what.startswith('open'):
            open_clip = clip
            for node, m in glb.motion(clip).items():
                moves[node] = m
            for node, r in glb.squeeze(clip).items():
                opens[node] = r
            continue
        if isinstance(what, str) and what.startswith('hide '):
            # a second mover (a maintenance hatch besides the door): the moved nodes are not drawn while tg shows it open
            for node in glb.motion(clip):
                hides.setdefault(node, []).extend(cond(c) for c in what[5:].split('|'))
            continue
        show, hide = glb.shown(clip)
        touched |= show | hide
        for c in ([what] if isinstance(what, str) else what):
            k, v = cond(c)
            for node in show:
                shows.setdefault(node, {}).setdefault(k, [])
                if v not in shows[node][k]:
                    shows[node][k].append(v)
    skip = set(spec.get('skip', []))
    parts = {}
    first = True
    # parts drawn in every state first: the rule's "model" part is one of them
    def conditional(n):
        own = spec.get('parts', {}).get(n, {})
        return n in touched or n in hides or n in moves or n in opens or n in flicks or n in spec.get('spin', {}) or any(k in own for k in ('states', 'exceptStates', 'overlays', 'exceptOverlays', 'spin'))
    for node in sorted(glb.mesh_nodes, key=conditional):
        if node in skip:
            continue
        frame = re.search(r'_Frame_(\d+)$', node)
        if frame and frame.group(1) != '0':
            continue  # a live frame plays the state's own animation: one frame of it is enough
        if spec.get('numbered') and re.search(r'_[1-9][0-9]*$', node):
            continue  # the same, exported as <state>_N
        if spec.get('firstFrames') and node not in spec.get('only', {}) and re.search(r' (frame )?[1-9][0-9]*( rear)?$', node):
            continue  # the same, exported as '<state> N' (the required models)
        base = {'file': spec['glb'], 'node': node}
        base.update(spec.get('part', {}))
        base.update(spec.get('parts', {}).get(node, {}))
        if node in moves:
            axis, deg, move = moves[node]
            base['pivot'] = True
            if axis:
                base['axis'], base['degrees'] = axis, deg
            if move:
                base['move'] = move
            if node in glb.carried:
                base['pivotAt'] = glb.carried[node]
        if node in opens:
            base['pivot'] = True
            base['openScale'] = opens[node]
        if node in flicks:
            axis, f = flicks[node]
            base['pivot'] = True
            if axis:
                if 'axis' in base and base['axis'] != axis:
                    raise SystemExit(f"{spec['id']}: {node} turns about two axes")
                base['axis'] = axis
            base['flick'] = f
        if node in spec.get('spin', {}):
            base['pivot'] = True
            base['axis'], base['spin'] = spec['spin'][node]
        for k, v in hides.get(node, []):
            base.setdefault({'states': 'exceptStates', 'overlays': 'exceptOverlays'}[k], []).append(v)
        variants = []
        if node in spec.get('only', {}):
            variants.append(dict(base, **spec['only'][node]))  # its conditions as the spec gives them, not as its clips would
        elif node in touched and node in shows:
            for k, values in shows[node].items():
                variants.append(dict(base, **{k: values}))
        elif node in touched or node in glb.hidden and node not in spec.get('always', []):
            continue  # hidden unless a clip we do not map shows it
        else:
            variants.append(base)
        for i, v in enumerate(variants):
            name = spec.get('names', {}).get(node) or ('model' if first else node)
            name += '' if i == 0 else '_' + str(i)
            first = first and name != 'model'
            parts[name] = v
    for name, part in spec.get('extra', {}).items():
        parts[name] = dict({'file': spec['glb']}, **part)
    e = {'id': spec['id']}
    if spec.get('family'):
        e['family'] = spec['family']
    for k in ('rotate',):
        if k in spec:
            e[k] = spec[k]
    if spec.get('awayFromWall'):
        e['dir'] = {'awayFromWall': True}
    e['icons'] = spec['icons']
    e['states'] = spec['states']
    for k in ('overlays', 'allOverlays'):
        if k in spec:
            e[k] = spec[k]
    e['rule'] = spec.get('rule', 'single')
    e['texture'] = 'model'
    for k in ('scale', 'turn', 'offset', 'multiTile', 'flatColors', 'rest', 'azimuth', 'overlayFrames', 'flickFrame'):
        if k in spec:
            e[k] = spec[k]
    w, h = spec.get('size', (2.0, 2.0))
    e['source'] = {'width': w, 'height': h}
    e['fit'] = spec.get('fit', {'width': 'tile', 'height': h})
    if open_clip:
        o = {}
        what = clips[open_clip]
        for c in what.split(None, 1)[1].split('|'):
            k, v = cond(c)
            o.setdefault(k, []).append(v)
        o['seconds'] = spec.get('seconds', glb.seconds(open_clip))
        if 'closedState' in spec:
            o['closedState'] = spec['closedState']  # a state the suffix rule would call open ('grill_open') that is not open
        e['open'] = o
    e['parts'] = parts
    return e


def dump(e):
    """One entry in the catalog's style: its fields on lines of their own, one part per line."""
    lines = ['    {']
    keys = [k for k in e if k != 'parts']
    for k in keys:
        lines.append(f'      {json.dumps(k)}: {json.dumps(e[k])},')
    items = list(e['parts'].items())
    if not items:
        lines.append('      "parts": {}')
        lines.append('    }')
        return chr(10).join(lines)
    lines.append('      "parts": {')
    for i, (k, v) in enumerate(items):
        lines.append(f'        {json.dumps(k)}: {json.dumps(v)}' + (',' if i < len(items) - 1 else ''))
    lines.append('      }')
    lines.append('    }')
    return '\n'.join(lines)


def main():
    text = CATALOG.read_text(encoding='utf-8-sig')
    head = text.split('\n' + MARKER + '\n')[0] if MARKER in text else None
    if head is None:
        # the first run: the generated entries follow the hand-written ones, before the models array closes
        end = text.rstrip().rstrip('}').rstrip().rstrip(']').rstrip()
        head = end + ','
        tail = '\n  ]\n}\n'
    else:
        tail = '\n  ]\n}\n'
    entries = [entry(s) for s in SPECS]
    ids = [e['id'] for e in entries]
    dup = {i for i in ids if ids.count(i) > 1}
    if dup:
        raise SystemExit(f'duplicate ids: {dup}')
    body = ',\n'.join(dump(e) for e in entries)
    CATALOG.write_text(head + '\n' + MARKER + '\n' + body + tail, encoding='utf-8')
    print(f'{len(entries)} entries, {sum(len(e["parts"]) for e in entries)} parts')


if __name__ == '__main__':
    main()
