using System.Text;

namespace Anomaly.Tools.Defines;

/// <summary>
/// Writes one C# file per tg source file that has emitted defines, mirroring its path without <c>code/</c>
/// (<c>code/__DEFINES/_flags.dm</c> gives <c>__DEFINES/_flags.g.cs</c>; translation-rules.md 1.1): a part of
/// <c>public static partial class Defines</c> in <c>Anomaly.Core.Tg</c> with the constants in source order, and a part
/// of <c>GlobalProcs</c> for the <c>span_*</c> methods. Each member carries the DM location and body and the tg doc
/// comment.
/// </summary>
public static class CSharpEmitter
{
    public const string Generator = "tools/Anomaly.Tools.Defines";

    public static string OutputPath(string sourceFile)
    {
        string path = sourceFile.StartsWith("code/", StringComparison.Ordinal) ? sourceFile.Substring(5) : sourceFile;
        return Path.ChangeExtension(path, null) + ".g.cs";
    }

    public static SortedDictionary<string, string> EmitAll(IEnumerable<DefineResult> results, string snapshot)
    {
        var files = new SortedDictionary<string, string>(StringComparer.Ordinal);
        foreach (IGrouping<string, DefineResult> group in results.Where(r => r.Emitted).GroupBy(r => r.Definition.File))
            files[OutputPath(group.Key)] = EmitFile(group.Key, group.ToList(), snapshot);
        return files;
    }

    private static string EmitFile(string sourceFile, List<DefineResult> members, string snapshot)
    {
        var sb = new StringBuilder();
        sb.Append("// <auto-generated/>\n");
        sb.Append($"// Generated from tgstation (snapshot {snapshot}): {sourceFile}\n");
        sb.Append($"// by {Generator}; do not edit (docs/ai/specs/defines-converter.md).\n");
        sb.Append("// Original copyright and license: tgstation, AGPL-3.0 (code). See ../tgstation/LICENSE.\n");
        sb.Append("namespace Anomaly.Core.Tg;\n");
        List<DefineResult> constants = members.Where(m => m.CsType != "method").ToList();
        List<DefineResult> methods = members.Where(m => m.CsType == "method").ToList();
        if (constants.Count > 0)
            EmitClass(sb, "Defines", constants);
        if (methods.Count > 0)
            EmitClass(sb, "GlobalProcs", methods);
        return sb.ToString();
    }

    private static void EmitClass(StringBuilder sb, string className, List<DefineResult> members)
    {
        sb.Append('\n');
        sb.Append($"public static partial class {className}\n");
        sb.Append("{\n");
        for (int i = 0; i < members.Count; i++)
        {
            if (i > 0)
                sb.Append('\n');
            EmitMember(sb, members[i]);
        }
        sb.Append("}\n");
    }

    private static void EmitMember(StringBuilder sb, DefineResult r)
    {
        MacroDefinition d = r.Definition;
        string parameters = d.IsFunctionLike ? "(" + string.Join(", ", d.Parameters.Select(p => p == "..." ? p : d.IsVariadic && p == d.Parameters[^1] ? p + "..." : p)) + ")" : "";
        sb.Append($"    // tg: {d.Location}  #define {d.Name}{parameters} {CSharpText.CommentLine(d.BodyText)}\n");
        var remarks = new List<string>(r.Notes);
        if (r.IndentedUnder != null)
            remarks.Add($"Indented under {r.IndentedUnder} in tg: one of its return values or argument indexes.");
        if (r.IndentedDefines.Count > 0)
            remarks.Add($"Indented under it in tg (return values or argument indexes): {string.Join(", ", r.IndentedDefines)}.");
        if (d.Doc != null)
        {
            sb.Append("    /// <summary>\n");
            foreach (string line in CSharpText.XmlDocLines(d.Doc))
                sb.Append(line.Length == 0 ? "    ///\n" : $"    /// {line}\n");
            sb.Append("    /// </summary>\n");
        }
        if (remarks.Count > 0)
        {
            sb.Append("    /// <remarks>\n");
            foreach (string remark in remarks)
            {
                foreach (string line in CSharpText.XmlDocLines(remark))
                    sb.Append($"    /// {line}\n");
            }
            sb.Append("    /// </remarks>\n");
        }
        if (r.CsType == "method")
            sb.Append($"    public static {r.CsSignature} => {r.CsValue};\n");
        else
            sb.Append($"    public const {r.CsType} {r.CsName} = {r.CsValue};\n");
    }
}
